// Prüft die vorausgefüllten Schreiben für den Todesfall: Auswahl, Inhalte, PDF.
import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
import { execFileSync } from 'child_process';
import path from 'path';
const hier = path.dirname(new URL(import.meta.url).pathname);
const url = 'file://' + path.join(hier, '../dist/klarordner.html');
const erg = path.join(hier, 'ergebnisse');
const spaeter = async (s) => { const d = s.locator('dialog[open]'); await d.waitFor({ timeout: 3000 }).catch(() => {}); if (await d.isVisible()) await s.click('dialog[open] #dialogKnoepfe button:last-child'); };
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const fehler = [];
const p = await (await browser.newContext({ locale: 'en-GB', viewport: { width: 1280, height: 900 } })).newPage();
await p.addInitScript(() => { delete window.showOpenFilePicker; delete window.showSaveFilePicker; window.print = () => { window.__gedruckt = (window.__gedruckt || 0) + 1; }; });
p.on('pageerror', e => fehler.push(e.message));
p.on('console', m => { if (m.type() === 'error') fehler.push(m.text()); });
await p.goto(url);
await p.setInputFiles('#dateiwahl', path.join(hier, 'testdaten.notfall.json'));
await spaeter(p);
// Bekannte Anbieter ergänzen: Netflix (nur online), Telekom (Brief mit Anleitung), Facebook (Gedenkzustand)
await p.evaluate(() => {
  zustand.daten.vertraege.push({ art: 'streaming', anbieter: 'Netflix', vertragsnummer: '', kosten: '', kuendigung: '', notiz: '' });
  zustand.daten.vertraege.push({ art: 'telefon', anbieter: 'Telekom Festnetz', vertragsnummer: 'K-4711', kosten: '', kuendigung: '', notiz: '' });
  zustand.daten.digital.konten.push({ kategorie: 'sozial', anbieter: 'Facebook', benutzername: 'erika.m', wunsch: 'gedenken', uebertragenAn: '', notiz: '' });
});
console.log('Anbieter-Vorschläge beim Tippen:', await p.locator('#anbieterListe option').count());
await p.click('#navliste li:nth-child(11) button');
await p.click('button:has-text("Prepare letters")');
console.log('Ansicht:', await p.textContent('#inhalt h2'));
const titel = await p.locator('.schreibzeile strong').allTextContents();
console.log('Schreiben:', titel.join(' | '));
const felder = p.locator('#inhalt .formkarte').nth(0).locator('input, textarea');
await p.fill('#inhalt input >> nth=0', 'Thomas Musterfrau');
await p.fill('#inhalt input >> nth=1', 'Sohn und Erbe');
await p.fill('#inhalt textarea >> nth=0', 'Am Markt 1\n12345 Beispielstadt');
await p.fill('#inhalt input[type=date]', '2026-09-20');
await p.fill('#inhalt input >> nth=3', 'Beispielstadt');
// Empfänger für das Streaming-Abo ändern
const zeile = p.locator('.schreibzeile', { hasText: 'Beispiel-Streaming' });
await zeile.locator('summary').click();
await zeile.locator('textarea').fill('Beispiel-Streaming GmbH\nPostfach 1\n10115 Berlin');
await p.click('button:has-text("Print selected letters")');
console.log('Druck aufgerufen:', await p.evaluate(() => window.__gedruckt), '| Briefe:', await p.evaluate(() => document.querySelectorAll('#druck .dbrief').length));
const druckSeiten = await p.evaluate(() => ({ alle: document.querySelectorAll('#druck .dbrief').length, anleitung: document.querySelectorAll('#druck .danleitung').length }));
const datei = path.join(erg, 'schreiben.pdf');
await p.pdf({ path: datei, preferCSSPageSize: true, printBackground: true });
const text = execFileSync('pdftotext', [datei, '-']).toString().replace(/\s+/g, ' ');
const seiten = Number(execFileSync('pdfinfo', [datei]).toString().match(/Pages:\s+(\d+)/)[1]);
const pruef = (was, ja) => console.log(`  ${ja ? 'ok ' : 'FEHLT'} ${was}`);
console.log('PDF Seiten:', seiten);
console.log('Seiten im Druck:', druckSeiten.alle, '| davon Anleitungen:', druckSeiten.anleitung);
pruef('Eine Seite pro Brief oder Anleitung', seiten === druckSeiten.alle);
pruef('Rentenservice-Adresse', text.includes('Niederlassung Renten Service 13497 Berlin'));
pruef('Rentenbrief mit Anleitung zum Vorschuss', text.includes('innerhalb von 30 Tagen nach dem Tod'));
pruef('Kein Vorschussantrag für den Sohn', !text.includes('beantrage ich den Vorschuss'));
pruef('Rundfunk-Adresse', text.includes('Beitragsservice 50656 Köln'));
pruef('Telekom: Brief an Bonn mit Kundennummer', text.includes('53171 Bonn') && text.includes('Kunden- oder Vertragsnummer K-4711'));
pruef('Netflix: nur Anleitung, Hinweis unbestätigt', text.includes('Netflix: Was ist zu tun?') && text.includes('kein eigenes Verfahren für Todesfälle veröffentlicht'));
pruef('Facebook: Anleitung Gedenkzustand', text.includes('Facebook: Was ist zu tun?') && text.includes('In Gedenkzustand versetzen'));
pruef('Sterbesatz', text.includes('Erika Musterfrau, geboren am 17.03.1952, zuletzt wohnhaft Lindenweg 4, 12345 Beispielstadt, ist am 20.09.2026 verstorben.'));
pruef('Absender', text.includes('Thomas Musterfrau') && text.includes('Am Markt 1'));
pruef('Beziehung', text.includes('als Sohn und Erbe der verstorbenen Person'));
pruef('Rentenservice', text.includes('Mitteilung über einen Sterbefall'));
pruef('Krankenkasse mit Versichertennummer', text.includes('Versichertennummer A123456789'));
pruef('Bank mit IBAN und Vollmacht', text.includes('Girokonto DE00 0000 0000 0000 0000 00') && text.includes('Vollmacht über den Tod hinaus zugunsten von Thomas Musterfrau'));
pruef('Sterbegeld-Meldung', text.includes('Meldung eines Todesfalls, Versicherungsnummer SG-0001') && text.includes('(Thomas Musterfrau)'));
pruef('Vermieter § 564 BGB', text.includes('§ 564 BGB'));
pruef('Rundfunk ohne Beitragsnummer', text.includes('Abmeldung wegen Todesfalls') && text.includes('Beitragsnummer ist mir nicht bekannt'));
pruef('Streaming mit geändertem Empfänger', text.includes('Beispiel-Streaming GmbH') && text.includes('Kündigung wegen Todesfalls'));
pruef('Online-Konto löschen', text.includes('Konto erika@example.org') && text.includes('löschen Sie alle dazu gespeicherten Daten'));
pruef('Ort und Datum', /Beispielstadt, \d\d\.\d\d\.\d{4}/.test(text));
pruef('Anlagen', text.includes('Anlagen: Kopie der Sterbeurkunde'));
pruef('Briefe auf Deutsch trotz englischer Oberfläche', !text.includes('Dear') && text.includes('Sehr geehrte Damen und Herren'));
pruef('Kein Kopf/Fuß mit Seitenzahl', !text.includes('Seite 1 von'));
execFileSync('pdftoppm', ['-r', '50', '-png', '-f', '1', '-l', '3', datei, path.join(erg, 'brief')]);
await p.evaluate(() => window.dispatchEvent(new Event('afterprint')));
// Gespeichert im Ordner
const gesp = await p.evaluate(() => ({ s: zustand.daten.schreiben.absender, e: Object.keys(zustand.daten.schreiben.empfaenger).length }));
console.log('Absender und Empfänger im Ordner gespeichert:', gesp.s === 'Thomas Musterfrau' && gesp.e === 1);
// Nichts ausgewählt
for (const b of await p.locator('.schreibliste input').all()) await b.uncheck();
await p.click('button:has-text("Print selected letters")');
console.log('Ohne Auswahl:', await p.textContent('#dialogTitel'));
console.log('Fehler:', fehler);
await browser.close();
